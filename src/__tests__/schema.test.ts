  it("should reject coach directives exceeding 30 words", () => {
    const longText =
      "This is a very long coaching directive that is meant to test the strict thirty word limit constraint and make sure that any long verbose response generated by the language model gets immediately flagged and rejected by the Zod runtime validation engine.";
    
    const wordCount = longText.trim().split(/\s+/).filter(Boolean).length;
    expect(wordCount).toBeGreaterThan(30);

    const parsed = Layer9ExecutionCoachSchema.safeParse({
      urgency: "EXECUTE",
      directiveText: longText,
      wordCount: wordCount,
      cueCategory: "technique",
      timestamp: new Date().toISOString(),
    });

    expect(parsed.success).toBe(false);
  });


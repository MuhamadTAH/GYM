        baselineLifts: {
          squat1RM: 140,
          benchPress1RM: 105,
          deadlift1RM: 180,
          overheadPress1RM: 70,
          barbellRow1RM: 90,
          pullUp1RM: 35,
        },
        injuryHistoryNotes: ["Mild left patellar tendinopathy 2024"],
